package org.example.constants;

/**
 * Constants class defining supported browser types for the test framework.
 * <p>
 * This class contains string constants representing the different browsers
 * that can be used with the WebDriverWrapper for test execution.
 * </p>
 *
 * @author Andrei Stoica
 * @version 1.0
 */
public class Browsers {
    /**
     * Constant for Google Chrome browser.
     */
    public static final String CHROME="chrome";
    
    /**
     * Constant for Microsoft Edge browser.
     */
    public static final String EDGE="edge";
    
    /**
     * Constant for Mozilla Firefox browser.
     */
    public static final String FIREFOX="firefox";
}
